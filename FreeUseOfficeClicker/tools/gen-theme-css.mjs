// Generates the THEME LAYER css block from tools/palette.mjs and splices it into
// index.html between the two sentinel comments.
//
//   node tools/gen-theme-css.mjs           write
//   node tools/gen-theme-css.mjs --print   dump to stdout only
//   node tools/gen-theme-css.mjs --audit   contrast report per theme
//
// Idempotent: re-running replaces the block in place, so palette edits are one command.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import {
    STRUCTURAL,
    SEMANTIC,
    EFFECTS,
    ACCENTS,
    VEILS,
    SHEENS,
    THEMES,
    valueFor,
    auditTheme,
} from './palette.mjs';
import { contrast } from './color-lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', 'index.html');

const BEGIN = '/* ==== FUOC THEME LAYER · GENERATED by tools/gen-theme-css.mjs — DO NOT EDIT BY HAND ==== */';
const END = '/* ==== END FUOC THEME LAYER ==== */';

const pad = (s, n) => s + ' '.repeat(Math.max(1, n - s.length));

function declFor(theme) {
    const lines = [];
    const group = (title) => lines.push(`        /* ${title} */`);

    group('design-system tokens (.fuoc-ui components)');
    for (const row of SEMANTIC) lines.push(`        ${pad(row[0] + ':', 22)}${valueFor(row[0], theme)};`);

    group('effects');
    for (const row of EFFECTS) lines.push(`        ${pad(row[0] + ':', 22)}${valueFor(row[0], theme)};`);

    group('legacy bridge · surfaces, lines, ink');
    for (const row of STRUCTURAL) lines.push(`        ${pad(row[0] + ':', 22)}${valueFor(row[0], theme)};`);

    group('legacy bridge · accents');
    for (const [token] of ACCENTS) lines.push(`        ${pad(token + ':', 22)}${valueFor(token, theme)};`);

    group('translucent fills (dark veils / white sheens)');
    for (const v of [...VEILS, ...SHEENS]) lines.push(`        ${pad(v.token + ':', 22)}${valueFor(v.token, theme)};`);

    return lines.join('\n');
}

function build() {
    const out = [];
    out.push(BEGIN);
    out.push(`    /*  ${THEMES.length} themes, ${SEMANTIC.length + EFFECTS.length + STRUCTURAL.length + ACCENTS.length + VEILS.length + SHEENS.length} tokens each.`);
    out.push('        The "dark" column reproduces the pre-theme values exactly, so switching a');
    out.push('        colour literal to its bridge token is a visual no-op on the default theme.');
    out.push('        Edit tools/palette.mjs, then run:  npm run theme:tokens                     */');

    for (const theme of THEMES) {
        const sel =
            theme.id === 'dark'
                ? ':root,\n    :root[data-fuoc-theme="dark"]'
                : `:root[data-fuoc-theme="${theme.id}"]`;
        out.push('');
        out.push(`    /* ── ${theme.label} (${theme.id}) ─────────────────────────────── */`);
        out.push(`    ${sel} {`);
        out.push(declFor(theme));
        out.push('    }');
    }

    // The page background itself has to follow the theme.
    out.push('');
    out.push('    /* Page canvas follows the active theme. */');
    out.push('    html[data-fuoc-theme] {');
    out.push('        background: var(--l-bg);');
    out.push('    }');
    out.push('    html[data-fuoc-theme] body {');
    out.push('        background-color: var(--l-bg);');
    out.push('        color: var(--l-ink);');
    out.push('    }');
    out.push('');
    out.push('    /* Light themes need dark form controls chrome (scrollbars, date pickers). */');
    out.push('    :root[data-fuoc-theme="light"] {');
    out.push('        color-scheme: light;');
    out.push('    }');
    out.push('    :root[data-fuoc-theme="dark"],');
    out.push('    :root[data-fuoc-theme="hc-dark"],');
    out.push('    :root[data-fuoc-theme="dim"] {');
    out.push('        color-scheme: dark;');
    out.push('    }');
    out.push(`    ${END}`);
    return out.join('\n');
}

function audit() {
    for (const theme of THEMES) {
        const rows = auditTheme(theme);
        const worst = rows.slice(0, 6);
        const inkOnPanel = contrast(valueFor('--l-ink', theme), valueFor('--l-panel', theme));
        const dimOnPanel = contrast(valueFor('--l-ink-dim', theme), valueFor('--l-panel', theme));
        const muteOnPanel = contrast(valueFor('--text-mute', theme), valueFor('--surface', theme));
        console.log(`\n${theme.label} (${theme.id})  page bg ${theme.pageBg}`);
        console.log(
            `  body ink ${inkOnPanel.toFixed(1)}:1   dim ink ${dimOnPanel.toFixed(1)}:1   muted ${muteOnPanel.toFixed(1)}:1`
        );
        console.log(
            '  lowest accents: ' + worst.map((w) => `${w.token.replace('--l-', '')} ${w.ratio.toFixed(1)}`).join(', ')
        );
        const failing = rows.filter((r) => r.ratio < 3);
        if (failing.length) console.log(`  ⚠ ${failing.length} accent(s) under 3:1 vs page bg`);
    }
}

const css = build();

if (process.argv.includes('--audit')) {
    audit();
} else if (process.argv.includes('--print')) {
    console.log(css);
} else {
    const src = await readFile(SRC, 'utf8');
    const startIdx = src.indexOf(BEGIN);
    let out;
    if (startIdx === -1) {
        console.error(
            'Sentinel not found. Insert these two lines inside the main <style> block first:\n' + BEGIN + '\n' + END
        );
        process.exit(1);
    }
    const endIdx = src.indexOf(END, startIdx);
    if (endIdx === -1) {
        console.error('Found BEGIN sentinel but no END sentinel.');
        process.exit(1);
    }
    out = src.slice(0, startIdx) + css + src.slice(endIdx + END.length);
    await writeFile(SRC, out, 'utf8');
    const tokens = SEMANTIC.length + EFFECTS.length + STRUCTURAL.length + ACCENTS.length + VEILS.length + SHEENS.length;
    console.log(
        `theme layer written: ${THEMES.length} themes × ${tokens} tokens (${(css.length / 1024).toFixed(1)} KB)`
    );
    audit();
}
