/* ---- Migration / canonicalization: removed & legacy race keys remap here ---- */
const RACE_REMAP = {
    dwarf:"halfling", robot:"cyborg", android:"cyborg", bunny:"rabbit", werewolf:"wolf", tiefling:"demon",
    incubus:"succubus", dragon:"dragonborn",
    catgirl:"cat", catboy:"cat", catkin:"cat",
    foxgirl:"fox", foxboy:"fox", foxkin:"fox",
    wolfgirl:"wolf", wolfboy:"wolf", wolfkin:"wolf",
    rabbitgirl:"rabbit", rabbitboy:"rabbit", rabbitkin:"rabbit", bunnykin:"rabbit", bunnygirl:"rabbit",
};
function canonicalRace(r) {
    if (!r) return "human";
    let k = String(r).toLowerCase().trim();
    let out = RACE_REMAP[k] || k;
    if (RACE_REMAP[out]) out = RACE_REMAP[out]; // resolve double-hop (e.g. android->robot->cyborg)
    return RACES[out] ? out : "human";          // unknown -> safe default, never throws
}
// Fold a saved raceSettings weight map onto canonical keys, summing remapped collisions.
function foldRaceWeights(src) {
    const out = {};
    Object.keys(RACES).forEach((k) => (out[k] = 0));
    if (src && "object" == typeof src)
        Object.keys(src).forEach((k) => {
            const cr = canonicalRace(k);
            out[cr] = (out[cr] || 0) + (parseInt(src[k]) || 0);
        });
    if (Object.values(out).reduce((a, b) => a + b, 0) <= 0) out.human = 100;
    return out;
}

