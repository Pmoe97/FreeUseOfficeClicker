function composeEyeDescriptor(plan, fields, bio) {
    const mode = plan && plan.eyeMode;
    // Strip glow words + trailing "eyes" the generator may have baked into the color
    // (deriveRaceFeaturesFromBio can leave "glowing eyes" in physical.eyes.color) so the
    // cyber glow prefix below doesn't double up ("glowing ... glowing eyes").
    const col = ((fields && fields.col) || "")
        .replace(/\b(none|faint|glowing|radiant)\b/gi, "")
        .replace(/\s*eyes?\s*$/i, "")
        .replace(/\s+/g, " ")
        .trim();
    // Some shapes carry "eyes" in the name (e.g. "doe eyes") — trim it so we don't double the noun.
    const shape = ((fields && fields.shape) || "").replace(/\s*eyes?\s*$/i, "").trim();
    if (mode === "gel") return `large glossy ${col} gel eyes`.replace(/\s+/g, " ").trim();
    if (mode === "cyber") {
        const glow = bio && bio.eyeGlow && bio.eyeGlow !== "none" ? bio.eyeGlow + " " : "glowing ";
        return `${glow}${shape ? shape + " " : ""}${col} cybernetic eyes`.replace(/\s+/g, " ").trim();
    }
    return null;
}
