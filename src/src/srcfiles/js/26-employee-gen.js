function generateUniqueName(e = "female", t = null, race = null) {
    gameState.usedEmployeeNames
        ? Array.isArray(gameState.usedEmployeeNames)
            ? (console.warn("[Names] usedEmployeeNames is an Array, converting to Set"),
              (gameState.usedEmployeeNames = new Set(gameState.usedEmployeeNames)))
            : "function" != typeof gameState.usedEmployeeNames.has &&
              (console.error("[Names] usedEmployeeNames is not a Set and has no .has() method, creating new Set"),
              (gameState.usedEmployeeNames = new Set()))
        : (console.warn("[Names] usedEmployeeNames not initialized, creating new Set"),
          (gameState.usedEmployeeNames = new Set())),
        gameState.onboarding &&
            Array.isArray(gameState.onboarding) &&
            gameState.onboarding.forEach((e) => {
                e.name && !gameState.usedEmployeeNames.has(e.name) && gameState.usedEmployeeNames.add(e.name);
            });
    let n = 0;
    const a = "male" === e || "transMan" === e,
        o = a ? MALE_FIRST_NAMES_POOL : FIRST_NAMES_POOL,
        i = getBaseEthnicity(t),
        s = i && ETHNIC_NAMES[i] ? ETHNIC_NAMES[i] : null;
    let r = null;
    s && ((r = a ? s.male : s.female), (r && 0 !== r.length) || (r = null));
    let l = s?.surnames;
    (l && 0 !== l.length) || (l = null);
    const raceDef = race ? RACES[canonicalRace(race)] : null,
        raceFirst = raceDef && Array.isArray(raceDef.namePool) && raceDef.namePool.length ? raceDef.namePool : null,
        raceSur = raceFirst && Array.isArray(raceDef.surnames) && raceDef.surnames.length ? raceDef.surnames : null;
    for (; n < 1e3; ) {
        let a2, i2;
        raceFirst
            ? ((a2 = Math.random() < 0.9 ? raceFirst[Math.floor(Math.random() * raceFirst.length)] : o[Math.floor(Math.random() * o.length)]),
              (i2 = raceSur ? raceSur[Math.floor(Math.random() * raceSur.length)] : ""))
            : ((a2 =
                  r && Math.random() < 0.6
                      ? r[Math.floor(Math.random() * r.length)]
                      : o[Math.floor(Math.random() * o.length)]),
              (i2 =
                  l && Math.random() < 0.75
                      ? l[Math.floor(Math.random() * l.length)]
                      : LAST_NAMES_POOL[Math.floor(Math.random() * LAST_NAMES_POOL.length)]));
        const s = i2 ? `${a2} ${i2}` : a2;
        if (!gameState.usedEmployeeNames.has(s)) {
            gameState.usedEmployeeNames.add(s);
            const n = t ? ` (ethnicity: ${t})` : "";
            return (
                console.log(
                    `[Names] Generated unique ${e} name: ${s}${n} (${gameState.usedEmployeeNames.size} names used)`
                ),
                s
            );
        }
        n++;
    }
    const c = `${o[Math.floor(Math.random() * o.length)]} ${LAST_NAMES_POOL[Math.floor(Math.random() * LAST_NAMES_POOL.length)]} ${Math.floor(1e3 * Math.random())}`;
    return gameState.usedEmployeeNames.add(c), console.warn(`[Names] Exhausted name pool, using suffix: ${c}`), c;
}
