function generateGiftPreferences(npc) {
    // Category affinity derived from personality so NPCs genuinely want different things.
    // A per-category jitter keeps identical personalities from being clones.
    const pers = (npc && npc.personality) || {},
        c = pers.confidence ?? 50,
        o = pers.outgoing ?? 50,
        f = pers.flirty ?? 50,
        pr = pers.professional ?? 50,
        inv = (x) => 100 - (x ?? 50),
        aff = {
            ROMANTIC: 0.7 * f + 0.3 * c,
            LUXURY: 0.6 * c + 0.2 * f + 0.2 * inv(pr),
            EXPERIENCES: 0.6 * o + 0.4 * c,
            TECH: 0.5 * pr + 0.5 * inv(f),
            INTELLECTUAL: 0.6 * pr + 0.4 * inv(o),
            FOOD: 0.5 * o + 25,
            PRACTICAL: 0.7 * pr + 0.3 * inv(c),
            QUIRKY: 0.6 * o + 0.4 * inv(pr),
            WELLNESS: 0.5 * c + 0.5 * pr,
            FASHION: 0.5 * f + 0.5 * c,
        },
        ranked = Object.keys(aff)
            .map((k) => ({ k, s: aff[k] + (50 * Math.random() - 25) }))
            .sort((x, y) => y.s - x.s),
        nLove = 2 + Math.floor(2 * Math.random()),
        nHate = 2 + Math.floor(2 * Math.random());
    return {
        loves: ranked.slice(0, nLove).map((x) => x.k),
        neutral: ranked.slice(nLove, ranked.length - nHate).map((x) => x.k),
        hates: ranked.slice(ranked.length - nHate).map((x) => x.k),
        learnedLoves: [],
        learnedHates: [],
        recentGifts: [],
        favoriteGifts: [],
        totalValue: 0,
        totalCount: 0,
        personalitySeeded: !!(npc && npc.personality),
    };
}
