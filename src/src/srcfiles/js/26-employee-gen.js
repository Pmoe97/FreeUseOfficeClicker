function interpolateImagePrompt(raceId, bio) {
    const race = RACES[canonicalRace(raceId)] || RACES.human;
    bio = bio || {};
    let s = (race.imagePrompt && race.imagePrompt.base) || "";
    s = s.replace(/\{(\w+)\}/g, (m, key) => {
        if (key === "allure") return race.allure && race.allure.length ? race.allure[Math.floor(Math.random() * race.allure.length)] : "";
        if (key === "gender") return bio.gender || "person";
        const v = bio[key];
        if (v === undefined || v === null || v === "" || v === "none") return "";
        if (typeof v === "boolean") return v ? key : "";
        if (typeof v === "string" && v[0] === "#") return nearestColorName(v);
        return String(v);
    });
    return s.replace(/\s+,/g, ",").replace(/,(\s*,)+/g, ",").replace(/\s{2,}/g, " ").replace(/\(\s*\)/g, "").trim();
}

